/**
 * Filter and search foods from the local database
 */
export function searchFoods(
  query: string,
  filter?: "all" | "high_protein" | "vegetarian" | "vegan" | "staples",
): FoodItem[] {
  const q = query.trim().toLowerCase();
  return FOOD_DATABASE.filter((item) => {
    if (filter === "high_protein" && !item.isHighProtein) return false;
    if (filter === "vegetarian" && !item.isVegetarian) return false;
    if (filter === "vegan" && !item.isVegan) return false;
    if (filter === "staples" && item.category !== "staple" && item.category !== "pulse_dal" && item.category !== "grain_bread") return false;

    if (!q) return true;
    const matchName = item.name.toLowerCase().includes(q);
    const matchBrand = item.brand ? item.brand.toLowerCase().includes(q) : false;
    const matchCat = item.category.toLowerCase().includes(q);
    return matchName || matchBrand || matchCat;
  });
}

/**
 * Barcode lookup resolver with mock scan support (D1)
 */
export function resolveBarcode(barcode: string): FoodItem | null {
  const cleanCode = barcode.trim();
  const match = FOOD_DATABASE.find((item) => item.barcode === cleanCode);
  return match ?? null;
}
